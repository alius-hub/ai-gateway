export function t(key: string, params?: Record<string, string | number>): string {
  const translated = locale.value === "en-US" ? english[key] ?? key : key;
  return params
    ? translated.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
    : translated;
}
